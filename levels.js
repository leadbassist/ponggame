// Math-defined layouts: test(x, y, column, row) with x/y centred on the grid.
const SHAPES = [
  (x, y, c, r) => r < 5,
  (x, y, c, r) => Math.abs(x) <= 0.5 + r * 0.5,
  (x, y) => Math.abs(x) >= 2 && Math.abs(y) >= 2,
  (x, y) => Math.abs(x) + Math.abs(y) <= 5.5,
  (x, y) => x * x + y * y <= 30,
  (x, y) => {
    const u = x / 4.6;
    const v = -y / 4.6 + 0.1;
    return (u * u + v * v - 1) ** 3 - u * u * v ** 3 <= 0;
  },
  (x, y) => Math.abs(x) <= Math.abs(y) + 0.5,
  (x, y, c, r) => c <= r,
  (x, y, c, r) => (r < 6 ? Math.abs(x) <= 0.5 + r * 0.55 : Math.abs(x) <= 1.5),
  (x, y) => x * x + y * y >= 12 && x * x + y * y <= 30,
  (x, y, c, r) => Math.abs(c - r) <= 1 || Math.abs(c + r - 11) <= 1,
  (x, y) => Math.abs(x) <= 1.5 || Math.abs(y) <= 1.5,
  (x, y, c, r) => (c + r) % 2 === 0 && r < 8,
  (x, y, c, r) => r % 2 === 0,
  (x, y, c) => c % 2 === 0,
  (x, y, c, r) => (c + r) % 3 !== 0,
  (x, y, c, r) => Math.abs(r - (5.5 + 3.5 * Math.sin(c * 0.8))) < 1.3,
  (x, y, c, r) => c - r >= 0 && c - r < 4,
  (x, y) => Math.floor(Math.max(Math.abs(x), Math.abs(y))) % 2 === 0,
  (x, y) => Math.floor(Math.abs(x) + Math.abs(y)) % 2 === 0,
  (x, y, c, r) => c % 2 === 0 && r % 2 === 0,
  (x, y, c, r) => c % 3 !== 2 && r < 9,
  (x, y, c, r) => r < 6 && Math.abs((c % 6) - 2.5) <= 0.5 + r * 0.5,
  (x, y, c, r) => r === 0 || r === 11 || c === 0 || c === 11 || (c >= 4 && c <= 7 && r >= 4 && r <= 7),
  (x, y, c, r) => {
    const d = x * x + y * y;
    const eyes = (c === 3 || c === 8) && (r === 3 || r === 4);
    const mouth = (r === 8 && c >= 3 && c <= 8) || (r === 7 && (c === 2 || c === 9));
    return (d >= 22 && d <= 32) || eyes || mouth;
  }
];

