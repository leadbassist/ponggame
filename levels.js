function gridFromShape(test) {
  return Array.from({ length: GRID_ROWS }, (_, r) =>
    Array.from({ length: GRID_COLUMNS }, (_, c) => Boolean(test(c - 5.5, r - 5.5, c, r))));
}

function gridFromAscii(lines) {
  return Array.from({ length: GRID_ROWS }, (_, r) =>
    Array.from({ length: GRID_COLUMNS }, (_, c) => lines[r]?.[c] === '#'));
}

function interleave(first, second) {
  const result = [];
  for (let index = 0; index < Math.max(first.length, second.length); index += 1) {
    if (first[index]) result.push(first[index]);
    if (second[index]) result.push(second[index]);
  }
  return result;
}

const LEVEL_GRIDS = interleave(ASCII_ART.map(gridFromAscii), SHAPES.map(gridFromShape));
